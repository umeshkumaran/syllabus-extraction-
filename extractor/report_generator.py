import datetime
import pymupdf as fitz

class PDFReportGenerator:
    """
    Generates a professional, multi-page PDF Extraction Report using PyMuPDF (fitz).
    Contains document overview, metadata, 8-signal confidence breakdown,
    and the full hierarchical syllabus structure with exact PDF page citations.
    """

    def __init__(self, doc_data):
        self.doc_data = doc_data
        self.pdf = fitz.open()
        self.current_page = None
        self.page_number = 0
        self.y = 55
        self.left = 40
        self.right = 555
        self.max_y = 790

    def new_page(self):
        self.current_page = self.pdf.new_page(width=595.28, height=841.89)
        self.page_number += 1
        self.y = 55
        self._draw_page_decorations()

    def _draw_page_decorations(self):
        p = self.current_page
        if self.page_number > 1:
            p.draw_line(fitz.Point(self.left, 38), fitz.Point(self.right, 38), color=(0.82, 0.86, 0.92), width=0.6)
            p.insert_text(fitz.Point(self.left, 32), "AI SYLLABUS PDF EXTRACTION REPORT", fontsize=8, fontname="hebo", color=(0.2, 0.35, 0.55))
            fn_sub = self.doc_data['filename'][:30]
            p.insert_text(fitz.Point(self.right - 140, 32), fn_sub, fontsize=8, fontname="helv", color=(0.45, 0.45, 0.45))

        # Bottom footer
        p.draw_line(fitz.Point(self.left, 810), fitz.Point(self.right, 810), color=(0.85, 0.88, 0.92), width=0.6)
        p.insert_text(fitz.Point(self.left, 822), "Generated by AI Syllabus PDF Chatbot • Page-Grounded Intelligence", fontsize=7.5, fontname="helv", color=(0.45, 0.45, 0.45))
        p.insert_text(fitz.Point(self.right - 50, 822), f"Page {self.page_number}", fontsize=7.5, fontname="helv", color=(0.45, 0.45, 0.45))

    def check_space(self, needed=20):
        if self.current_page is None or self.y + needed > self.max_y:
            self.new_page()

    def add_title(self, text, subtitle=None):
        self.check_space(60)
        p = self.current_page
        # Header banner box
        p.draw_rect(fitz.Rect(self.left, self.y, self.right, self.y + 44), color=None, fill=(0.04, 0.1, 0.22))
        p.insert_text(fitz.Point(self.left + 14, self.y + 26), text, fontsize=15, fontname="hebo", color=(0.0, 0.95, 1.0))
        if subtitle:
            p.insert_text(fitz.Point(self.left + 14, self.y + 38), subtitle, fontsize=8.5, fontname="helv", color=(0.8, 0.88, 0.95))
        self.y += 56

    def add_section_header(self, text):
        self.check_space(34)
        p = self.current_page
        p.draw_rect(fitz.Rect(self.left, self.y, self.right, self.y + 20), color=None, fill=(0.92, 0.95, 0.98))
        p.insert_text(fitz.Point(self.left + 8, self.y + 14), text, fontsize=10.5, fontname="hebo", color=(0.08, 0.2, 0.38))
        self.y += 26

    def add_key_value(self, key, value, page_ref=None):
        self.check_space(16)
        p = self.current_page
        p.insert_text(fitz.Point(self.left + 8, self.y + 10), f"{key}:", fontsize=8.5, fontname="hebo", color=(0.2, 0.25, 0.3))
        p.insert_text(fitz.Point(self.left + 150, self.y + 10), str(value), fontsize=8.5, fontname="helv", color=(0.1, 0.1, 0.1))
        if page_ref:
            p.insert_text(fitz.Point(self.right - 80, self.y + 10), f"Source: Page {page_ref}", fontsize=7.5, fontname="helv", color=(0.45, 0.45, 0.45))
        self.y += 15

    def add_course_header(self, text, page_ref):
        self.check_space(26)
        p = self.current_page
        p.draw_rect(fitz.Rect(self.left + 4, self.y, self.right - 4, self.y + 18), color=(0.8, 0.85, 0.9), fill=(0.96, 0.98, 1.0), width=0.5)
        p.insert_text(fitz.Point(self.left + 10, self.y + 12), text, fontsize=9.5, fontname="hebo", color=(0.05, 0.25, 0.55))
        if page_ref:
            p.insert_text(fitz.Point(self.right - 85, self.y + 12), f"Source: Page {page_ref}", fontsize=8, fontname="helv", color=(0.4, 0.4, 0.4))
        self.y += 22

    def add_unit_header(self, text, page_ref):
        self.check_space(18)
        p = self.current_page
        p.insert_text(fitz.Point(self.left + 14, self.y + 10), text, fontsize=9, fontname="hebo", color=(0.1, 0.45, 0.3))
        if page_ref:
            p.insert_text(fitz.Point(self.right - 75, self.y + 10), f"Page {page_ref}", fontsize=7.5, fontname="helv", color=(0.5, 0.5, 0.5))
        self.y += 15

    def add_bullet(self, text, page_ref=None, indent=24, is_sub=False):
        bullet_sym = "-" if is_sub else "•"
        color = (0.35, 0.35, 0.35) if is_sub else (0.15, 0.15, 0.15)
        fontname = "helv"
        fontsize = 7.8 if is_sub else 8.4

        max_char_len = 78 if not is_sub else 72
        words = text.split()
        lines = []
        curr = ""
        for w in words:
            if len(curr) + len(w) + 1 <= max_char_len:
                curr += (" " if curr else "") + w
            else:
                lines.append(curr)
                curr = w
        if curr:
            lines.append(curr)

        for i, l in enumerate(lines):
            self.check_space(14)
            p = self.current_page
            prefix = f"{bullet_sym} " if i == 0 else "   "
            p.insert_text(fitz.Point(self.left + indent, self.y + 9), prefix + l, fontsize=fontsize, fontname=fontname, color=color)
            if i == 0 and page_ref:
                p.insert_text(fitz.Point(self.right - 65, self.y + 9), f"Page {page_ref}", fontsize=7.2, fontname="helv", color=(0.5, 0.5, 0.5))
            self.y += 13

    def add_table(self, rows):
        if not rows:
            return
        cols = len(rows[0])
        col_w = (self.right - self.left - 20) / max(1, cols)

        for r_idx, row in enumerate(rows[:25]):
            self.check_space(16)
            p = self.current_page
            is_head = (r_idx == 0)
            bg = (0.9, 0.93, 0.97) if is_head else ((0.98, 0.98, 0.98) if r_idx % 2 == 1 else (1.0, 1.0, 1.0))
            p.draw_rect(fitz.Rect(self.left + 10, self.y, self.right - 10, self.y + 15), color=(0.85, 0.85, 0.85), fill=bg, width=0.3)
            
            for c_idx, cell in enumerate(row):
                cell_text = str(cell)[:18]
                x_pos = self.left + 14 + (c_idx * col_w)
                fn = "hebo" if is_head else "helv"
                p.insert_text(fitz.Point(x_pos, self.y + 10), cell_text, fontsize=7.2, fontname=fn, color=(0.1, 0.1, 0.1))
            self.y += 15
        self.y += 8

    def build(self):
        doc = self.doc_data
        h = doc['hierarchy']
        conf = doc['confidence']

        # 1. Title Banner
        date_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
        self.add_title("AI SYLLABUS PDF EXTRACTION REPORT", f"Generated on {date_str} • Document: {doc['filename']}")

        # 2. Document Summary Section
        self.add_section_header("1. Document Overview & Metadata")
        self.add_key_value("Source Document", doc['filename'])
        self.add_key_value("Total Document Pages", doc['total_pages'])
        self.add_key_value("Courses Detected", h.get('total_courses', 0))
        self.add_key_value("Overall Extraction Confidence", f"{conf['overall']}%")

        if h.get("institution"):
            self.add_key_value("Institution", h['institution']['name'], h['institution']['page'])
        if h.get("programme"):
            self.add_key_value("Programme", h['programme']['name'], h['programme']['page'])
        if h.get("department"):
            self.add_key_value("Department / Branch", h['department']['name'], h['department']['page'])
        if h.get("batch_year"):
            self.add_key_value("Regulation / Batch", h['batch_year']['val'], h['batch_year']['page'])

        self.y += 10

        # 3. Estimated Extraction Confidence Breakdown
        self.add_section_header("2. Estimated Extraction Confidence Audit")
        self.add_key_value("Text Extraction Quality", f"{conf['text_extraction']}%")
        self.add_key_value("OCR Performance Score", f"{conf['ocr']}%")
        self.add_key_value("Course Detection", f"{conf['course_detection']}%")
        self.add_key_value("Unit Detection", f"{conf['unit_detection']}%")
        self.add_key_value("Topic Coverage", f"{conf['topic_detection']}%")
        self.add_key_value("Table Detection", f"{conf.get('table_detection', 0)}%")
        self.add_key_value("Outcome Detection", f"{conf.get('outcome_detection', 0)}%")
        self.add_key_value("Weighted Overall Confidence", f"{conf['overall']}%")

        self.y += 10

        # 4. Hierarchical Syllabus Structure
        self.add_section_header("3. Hierarchical Syllabus Structure")

        courses = h.get("courses", [])
        if not courses:
            self.add_bullet("No structured courses detected in syllabus.")
        
        for c in courses:
            cred = c.get("credits_info")
            cred_str = f" [Credits: {cred['C']}]" if cred and 'C' in cred else ""
            c_header = f"{c.get('code', 'CRS')} - {c.get('title', 'Course')}{cred_str}"
            self.add_course_header(c_header, c.get('start_page'))

            # Units
            units = c.get("units", [])
            for u in units:
                hrs = f" ({u['hours']} Hours)" if u.get("hours") else ""
                u_text = f"Unit {u.get('unit_number')}: {u.get('title')}{hrs}"
                self.add_unit_header(u_text, u.get('page'))

                for t in u.get("topics", []):
                    self.add_bullet(t.get('title'), t.get('page'), indent=22)
                    for st in t.get("subtopics", []):
                        self.add_bullet(st.get('title'), st.get('page'), indent=32, is_sub=True)

            # Course Outcomes
            if c.get("outcomes"):
                self.check_space(16)
                self.current_page.insert_text(fitz.Point(self.left + 14, self.y + 10), "Course Outcomes:", fontsize=8.5, fontname="hebo", color=(0.3, 0.2, 0.5))
                self.y += 14
                for co in c["outcomes"]:
                    bl = f" [Bloom: {co['bloom_level']} ({co['bloom_source']})]" if co.get('bloom_level') else ""
                    self.add_bullet(f"{co['text']}{bl}", co.get('page'), indent=22)

            # Textbooks
            if c.get("textbooks"):
                self.check_space(16)
                self.current_page.insert_text(fitz.Point(self.left + 14, self.y + 10), "Text Books:", fontsize=8.5, fontname="hebo", color=(0.4, 0.25, 0.1))
                self.y += 14
                for tb in c["textbooks"]:
                    self.add_bullet(tb['title'], tb.get('page'), indent=22)

            # Reference Books
            if c.get("reference_books"):
                self.check_space(16)
                self.current_page.insert_text(fitz.Point(self.left + 14, self.y + 10), "Reference Books:", fontsize=8.5, fontname="hebo", color=(0.4, 0.25, 0.1))
                self.y += 14
                for rb in c["reference_books"]:
                    self.add_bullet(rb['title'], rb.get('page'), indent=22)

            # CO-PO Matrix
            if c.get("co_po_matrix"):
                mat = c["co_po_matrix"][0]
                self.check_space(20)
                self.current_page.insert_text(fitz.Point(self.left + 14, self.y + 10), f"CO-PO Mapping Matrix (Page {mat.get('page')}):", fontsize=8.5, fontname="hebo", color=(0.2, 0.35, 0.5))
                self.y += 14
                self.add_table(mat.get("matrix", []))

            self.y += 8

        # Generate and return PDF bytes
        pdf_bytes = self.pdf.tobytes(deflate=True)
        self.pdf.close()
        return pdf_bytes
